/**
 * Strips all markdown symbols so the speech synthesizer NEVER reads "asterisco", "hashtag", etc.
 */
export function sanitizeForNarration(text) {
  if (!text) return '';
  return text
    .replace(/\*\*/g, '')          // remove bold **
    .replace(/\*/g, '')           // remove single *
    .replace(/_{1,2}/g, '')       // remove underscores _
    .replace(/#{1,6}\s*/g, '')    // remove headers #
    .replace(/[`~]/g, '')         // remove code ticks / strikethrough
    .replace(/[\[\]\(\)\{\}]/g, '') // remove brackets
    .replace(/["'“”«»]/g, '')     // clean quotes
    .replace(/[-–—]{2,}/g, ', ')  // replace dashes with pause
    .replace(/\s+/g, ' ')         // normalize spaces
    .trim();
}

/**
 * Resolves a 100% reliable, zero-limit high-definition image matching the sentence topic
 * NEVER uses third-party rate-limited endpoints.
 */
export function getReliableSceneImage(sentence = '', index = 0, work = '', atmosphereId = 'epic') {
  const text = (sentence + ' ' + work).toLowerCase();

  // 1. Topic: Grass / Nature / Plants / Swamp
  if (/grama|mato|campo|floresta|árvore|natureza|verde|pântano|folhas|jardim|terra|lama/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.grass;
    return list[index % list.length];
  }

  // 2. Topic: Space / Stars / Planets / Black Hole
  if (/espaço|estrela|planeta|nave|buraco negro|galáxia|universo|cósmico|vórtice|interestelar|gravidade/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.space;
    return list[index % list.length];
  }

  // 3. Topic: Ocean / Sea / Water / Iceberg / Ship / Submarine
  if (/iceberg|gelo|navio|oceano|mar|água|abismo|afundou|sereia|submarino|ondas|titanic/i.test(text)) {
    if (/iceberg|gelo|congelad/i.test(text)) {
      return TOPIC_IMAGE_LIBRARY.ice[index % TOPIC_IMAGE_LIBRARY.ice.length];
    }
    const list = TOPIC_IMAGE_LIBRARY.ocean;
    return list[index % list.length];
  }

  // 4. Topic: Fire / Explosions / War / Destruction
  if (/fogo|chamas|explosão|queim|cinzas|raio|batalha|destruição|vulcão/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.fire;
    return list[index % list.length];
  }

  // 5. Topic: Toys / Dolls / Child bedroom
  if (/brinquedo|boneco|woody|quarto|andy|infância|criança|pelúcia/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.toys;
    return list[index % list.length];
  }

  // 6. Topic: Castle / King / Throne / Medieval
  if (/castelo|rei|trono|coroa|reino|espada|armadura|cavaleiro|farquaad|shrek/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.castle;
    return list[index % list.length];
  }

  // 7. Topic: City / Neon / Streets / Cyberpunk
  if (/cidade|rua|neon|prédio|balada|carro|futuro|multidão|metrópole/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.city;
    return list[index % list.length];
  }

  // 8. Topic: Darkness / Ghost / Fear / Nightmare
  if (/sombra|pesadelo|escuro|terror|fantasma|demônio|morte|sangue|grito|medo/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.darkness;
    return list[index % list.length];
  }

  // 9. Topic: Sun / Light / Joy / Hug / Rainbow
  if (/sol|ouro|luz|abraço|amor|alegria|amanhecer|sorriso|festa|paz|vitória/i.test(text)) {
    const list = TOPIC_IMAGE_LIBRARY.sun;
    return list[index % list.length];
  }

  // Fallbacks based on atmosphere
  if (atmosphereId === 'horror') {
    return TOPIC_IMAGE_LIBRARY.darkness[index % TOPIC_IMAGE_LIBRARY.darkness.length];
  }
  if (atmosphereId === 'happy') {
    return TOPIC_IMAGE_LIBRARY.sun[index % TOPIC_IMAGE_LIBRARY.sun.length];
  }
  if (atmosphereId === 'comedy') {
    return TOPIC_IMAGE_LIBRARY.city[index % TOPIC_IMAGE_LIBRARY.city.length];
  }

  return TOPIC_IMAGE_LIBRARY.space[index % TOPIC_IMAGE_LIBRARY.space.length];
}

